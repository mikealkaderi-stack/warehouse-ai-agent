-- SRT accounting, suppliers, expenses, employees, compensation and payroll.
-- Additive migration: existing drivers, trips, regions, vehicles and trip_details
-- are not replaced or rewritten.

create extension if not exists btree_gist;

create table public.accounts (
    id bigint generated by default as identity primary key,
    code text not null unique check (btrim(code) <> ''),
    name text not null check (btrim(name) <> ''),
    account_type text not null check (account_type in ('asset','liability','equity','revenue','expense')),
    normal_balance text not null check (normal_balance in ('debit','credit')),
    parent_id bigint references public.accounts(id),
    is_control_account boolean not null default false,
    is_system boolean not null default false,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (parent_id is null or parent_id <> id)
);

create table public.journal_entries (
    id bigint generated by default as identity primary key,
    entry_number text not null unique,
    entry_date date not null,
    description text not null check (btrim(description) <> ''),
    reference text,
    source_type text not null default 'manual',
    source_id text,
    status text not null default 'draft' check (status in ('draft','posted','voided')),
    posted_at timestamptz,
    posted_by uuid references auth.users(id),
    reversal_of_id bigint references public.journal_entries(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check ((status = 'posted' and posted_at is not null) or status <> 'posted')
);

create unique index journal_entries_source_unique
    on public.journal_entries(source_type, source_id)
    where source_id is not null and status <> 'voided';

create table public.journal_lines (
    id bigint generated by default as identity primary key,
    journal_entry_id bigint not null references public.journal_entries(id) on delete cascade,
    line_number integer not null check (line_number > 0),
    account_id bigint not null references public.accounts(id),
    description text,
    debit numeric(14,2) not null default 0 check (debit >= 0),
    credit numeric(14,2) not null default 0 check (credit >= 0),
    created_at timestamptz not null default now(),
    unique (journal_entry_id, line_number),
    check ((debit > 0 and credit = 0) or (credit > 0 and debit = 0))
);

create index journal_lines_account_idx on public.journal_lines(account_id);
create index journal_entries_date_idx on public.journal_entries(entry_date, id);

