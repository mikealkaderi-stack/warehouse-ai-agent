create view public.general_ledger as
select je.id journal_entry_id, je.entry_number, je.entry_date, je.description entry_description,
       je.reference, je.source_type, je.source_id, jl.line_number, a.id account_id,
       a.code account_code, a.name account_name, a.account_type, jl.description line_description,
       jl.debit, jl.credit
from public.journal_entries je
join public.journal_lines jl on jl.journal_entry_id=je.id
join public.accounts a on a.id=jl.account_id
where je.status='posted';

create view public.account_balances as
select a.id, a.code, a.name, a.account_type, a.normal_balance,
       coalesce(sum(gl.debit),0)::numeric(14,2) total_debit,
       coalesce(sum(gl.credit),0)::numeric(14,2) total_credit,
       case when a.normal_balance='debit'
            then (coalesce(sum(gl.debit),0)-coalesce(sum(gl.credit),0))::numeric(14,2)
            else (coalesce(sum(gl.credit),0)-coalesce(sum(gl.debit),0))::numeric(14,2) end balance
from public.accounts a left join public.general_ledger gl on gl.account_id=a.id
group by a.id, a.code, a.name, a.account_type, a.normal_balance;

-- Opening balances: one balanced, posted journal created from simple inputs.
create or replace function public.create_opening_balances(
    opening_date date, cash_amount numeric, mgt_payable numeric, arcome_payable numeric
) returns bigint language plpgsql security definer set search_path=public as $$
declare entry_id bigint; cash_id bigint; mgt_id bigint; arcome_id bigint; equity_id bigint; difference numeric;
begin
    if exists(select 1 from public.journal_entries where source_type='opening_balance' and status<>'voided') then
        raise exception 'Opening balances have already been created.';
    end if;
    if least(cash_amount,mgt_payable,arcome_payable) < 0 then raise exception 'Opening balances cannot be negative.'; end if;
    select id into cash_id from public.accounts where code='1000';
    select id into mgt_id from public.accounts where code='2001';
    select id into arcome_id from public.accounts where code='2002';
    select id into equity_id from public.accounts where code='3100';
    insert into public.journal_entries(entry_number,entry_date,description,source_type,source_id)
    values(public.next_document_number('JE','public.journal_entry_number_seq'),opening_date,'Opening balances','opening_balance','initial') returning id into entry_id;
    if cash_amount>0 then insert into public.journal_lines values(default,entry_id,1,cash_id,'Opening cash',cash_amount,0,default); end if;
    if mgt_payable>0 then insert into public.journal_lines values(default,entry_id,2,mgt_id,'Opening MGT payable',0,mgt_payable,default); end if;
    if arcome_payable>0 then insert into public.journal_lines values(default,entry_id,3,arcome_id,'Opening Arcome payable',0,arcome_payable,default); end if;
    difference := mgt_payable + arcome_payable - cash_amount;
    if difference>0 then insert into public.journal_lines values(default,entry_id,4,equity_id,'Opening balance equity',difference,0,default);
    elsif difference<0 then insert into public.journal_lines values(default,entry_id,4,equity_id,'Opening balance equity',0,-difference,default); end if;
    perform public.post_journal(entry_id); return entry_id;
end;
$$;

-- RLS follows the existing private single-user authorization model.
do $$ declare table_name text; begin
    foreach table_name in array array['accounts','journal_entries','journal_lines','suppliers','supplier_invoices','supplier_payments','expense_transactions','positions','employees','employee_salary_history','commission_schemes','commission_scheme_versions','commission_tiers','driver_compensation_history','payroll_runs','payroll_items'] loop
        execute format('alter table public.%I enable row level security',table_name);
        execute format('grant select,insert,update,delete on public.%I to authenticated',table_name);
        execute format('create policy "SRT authorized access" on public.%I for all to authenticated using ((select public.is_srt_authorized())) with check ((select public.is_srt_authorized()))',table_name);
    end loop;
end $$;

