create or replace function public.next_document_number(prefix text, sequence_name regclass)
returns text language plpgsql volatile set search_path = public as $$
declare next_value bigint;
begin
    execute format('select nextval(%L)', sequence_name::text) into next_value;
    return prefix || '-' || lpad(next_value::text, 6, '0');
end;
$$;

create or replace function public.validate_commission_tiers(version_id bigint)
returns void language plpgsql set search_path = public as $$
declare invalid_count integer;
begin
    with ordered as (
        select minimum_orders, maximum_orders,
               lag(maximum_orders) over (order by minimum_orders) previous_max,
               lead(minimum_orders) over (order by minimum_orders) next_min
        from public.commission_tiers
        where commission_scheme_version_id = version_id
    )
    select count(*) into invalid_count from ordered
    where minimum_orders <> 0 and previous_max is null
       or previous_max is not null and minimum_orders <> previous_max + 1
       or maximum_orders is null and next_min is not null;

    if invalid_count > 0 or not exists (
        select 1 from public.commission_tiers
        where commission_scheme_version_id = version_id and maximum_orders is null
    ) then
        raise exception 'Commission tiers must start at 0, be continuous, not overlap, and finish with no maximum.';
    end if;
end;
$$;

create or replace function public.post_journal(entry_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare debit_total numeric(14,2); credit_total numeric(14,2); current_status text;
begin
    select status into current_status from public.journal_entries where id = entry_id for update;
    if current_status is null then raise exception 'Journal entry not found.'; end if;
    if current_status <> 'draft' then raise exception 'Only draft journals can be posted.'; end if;
    select coalesce(sum(debit),0), coalesce(sum(credit),0)
      into debit_total, credit_total from public.journal_lines where journal_entry_id = entry_id;
    if debit_total <= 0 or debit_total <> credit_total then
        raise exception 'Journal entry must be balanced and greater than zero.';
    end if;
    update public.journal_entries set status='posted', posted_at=now(), posted_by=auth.uid(), updated_at=now()
    where id=entry_id;
end;
$$;

create or replace function public.guard_posted_journal_entry()
returns trigger language plpgsql as $$
begin
    if old.status = 'posted' then
        raise exception 'Posted journal entries are immutable; create a reversal instead.';
    end if;
    return coalesce(new,old);
end;
$$;

create or replace function public.guard_posted_journal_line()
returns trigger language plpgsql as $$
declare target_entry_id bigint;
begin
    target_entry_id := case when tg_op='DELETE' then old.journal_entry_id else new.journal_entry_id end;
    if exists (
        select 1 from public.journal_entries where id=target_entry_id and status='posted'
    ) then
        raise exception 'Lines of a posted journal entry are immutable.';
    end if;
    return coalesce(new,old);
end;
$$;

create trigger guard_posted_journal_entry before update or delete on public.journal_entries
for each row execute function public.guard_posted_journal_entry();
create trigger guard_posted_journal_lines before update or delete on public.journal_lines
for each row execute function public.guard_posted_journal_line();

create or replace function public.guard_locked_payroll_run()
returns trigger language plpgsql as $$
begin
    if old.status in ('approved','paid') then
        raise exception 'Approved or paid payroll is immutable.';
    end if;
    return coalesce(new,old);
end;
$$;

create or replace function public.guard_locked_payroll_item()
returns trigger language plpgsql as $$
declare target_run_id bigint;
begin
    target_run_id := case when tg_op='DELETE' then old.payroll_run_id else new.payroll_run_id end;
